    private function seedProductForStore(array $item, array $storeDef, User $owner, array $cats): Product
    {
        $sku   = $storeDef['prefix'] . '-' . $item['sku'];
        $price = round($item['price'] * $storeDef['price_factor'], 2);
        $stock = max(1, (int) round($item['stock_quantity'] * $storeDef['stock_factor']));

        $product = Product::updateOrCreate(
            ['sku' => $sku],
            [
                'user_id'            => $owner->id,
                'category_id'        => $cats[$item['cat_slug']] ?? null,
                'category'           => $item['category'],
                'name'               => $item['name'],
                'brand'              => $item['brand'],
                'product_type'       => $item['product_type'],
                'description'        => $item['description'],
                'package_size'       => $item['package_size'] ?? 1,
                'package_unit'       => $item['package_unit'] ?? 'piece',
                'packaging_type'     => $item['packaging_type'] ?? 'None',
                'price'              => $price,
                'price_unit'         => $item['price_unit'],
                'stock_quantity'     => $stock,
                'stock_unit'         => $item['stock_unit'],
                'reorder_threshold'  => $item['reorder_threshold'],
                'recommended_season' => $item['recommended_season'] ?? 'both',
                'status'             => 'active',
            ]
        );

        if (!empty($item['npk'])) {
            FertilizerDetail::updateOrCreate(
                ['product_id' => $product->id],
                [
                    'nitrogen_percentage'   => $item['npk'][0],
                    'phosphorus_percentage' => $item['npk'][1],
                    'potassium_percentage'  => $item['npk'][2],
                    'form_type'             => $item['form_type'] ?? 'Granular',
                    'application_rate_min'  => $item['fert_rate_min'] ?? null,
                    'application_rate_max'  => $item['fert_rate_max'] ?? null,
                    'application_rate_unit' => $item['fert_rate_unit'] ?? 'kg/ha',
                    'application_method'    => $item['fert_method'] ?? null,
                    'application_timing'    => $item['fert_timing'] ?? null,
                ]
            );
        }

        foreach ($item['applications'] ?? [] as $app) {
            $crop = Crop::whereRaw('LOWER(name) = ?', [strtolower($app['crop'])])->first();
            ProductApplication::updateOrCreate(
                ['product_id' => $product->id, 'crop_id' => $crop?->id],
                [
                    'application_rate_min'  => $app['rate_min'],
                    'application_rate_max'  => $app['rate_max'] ?? $app['rate_min'],
                    'application_rate_unit' => $app['unit'] ?? 'kg/ha',
                    'application_method'    => $app['method'] ?? 'Broadcasting',
                    'application_timing'    => $app['timing'] ?? null,
                    'notes'                 => $app['notes'] ?? null,
                ]
            );
        }

        // DecisionFormula records are what make a product appear in
        // the farmer quotation page for a given crop + season.
        foreach ($item['formulas'] ?? [] as $f) {
            DecisionFormula::updateOrCreate(
                ['crop_type' => $f['crop'], 'season' => $f['season'], 'product_id' => $product->id],
                [
                    'rate_per_hectare' => $f['rate'],
                    'unit'             => $f['unit'],
                    'notes'            => $f['notes'] ?? null,
                ]
            );
        }

        return $product;
    }

